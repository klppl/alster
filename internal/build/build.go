const marker = ".alster-output"

type Page struct {
	markdown.Meta
	Group, URL, CoverURL string
	CoverImage           images.Variant
	HTML                 template.HTML
}
type Group struct {
	Name  string
	Pages []Page
}
type view struct {
	Site                                  config.Config
	Prefix, Title, Description, Canonical string
	Section                               string
	Page                                  *Page
	Groups                                []Group
	Tags                                  []string
	Posts                                 []Page
	Featured                              []Page
	Activity                              []Page
	IntroTitle                            string
	IntroHTML                             template.HTML
}

func nested(a, b string) bool {
	rel, err := filepath.Rel(a, b)
	return err == nil && rel != ".." && !strings.HasPrefix(rel, ".."+string(filepath.Separator))
}

func isFrontpageFile(rel string) bool {
	base := strings.ToLower(path.Base(rel))
	if !strings.Contains(rel, "/") {
		switch base {
		case "index.md", "_index.md", "home.md", "frontpage.md", "frontpage-about.md":
			return true
		}
	}
	return base == "frontpage-about.md" || base == "frontpage.md" || base == "home.md"
}

// Run stages a complete build before replacing only an Alster-owned output tree.
func Run(c config.Config) error {
	if err := config.ValidateBaseURL(c.BaseURL); err != nil {
		return err
	}
	outputPath, err := resolvedPath(c.Output)
	if err != nil {
		return err
	}
	for _, input := range []string{c.Content, c.Templates} {
		inputPath, err := resolvedPath(input)
		if err != nil {
			return err
		}
		if nested(outputPath, inputPath) || nested(inputPath, outputPath) {
			return fmt.Errorf("output must not overlap content or templates")
		}
	}
	if info, err := os.Lstat(c.Output); err == nil {
		if !info.IsDir() || info.Mode()&os.ModeSymlink != 0 {
			return fmt.Errorf("output must be a regular directory")
		}
		if _, err := os.Stat(filepath.Join(c.Output, marker)); err != nil {
			return fmt.Errorf("refusing to replace output without %s marker: %s", marker, c.Output)
		}
	} else if !os.IsNotExist(err) {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(c.Output), 0755); err != nil {
		return err
	}
	stage, err := os.MkdirTemp(filepath.Dir(c.Output), ".alster-build-")
	if err != nil {
		return err
	}
	defer os.RemoveAll(stage)
	if err := generate(c, stage); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(stage, marker), []byte("Generated by Alster. This directory is replaced on build.\n"), 0644); err != nil {
		return err
	}
	backup := stage + "-previous"
	if _, err := os.Stat(c.Output); err == nil {
		if err := os.Rename(c.Output, backup); err != nil {
			return err
		}
	}
	if err := os.Rename(stage, c.Output); err != nil {
		if _, e := os.Stat(backup); e == nil {
			if e = os.Rename(backup, c.Output); e != nil {
				return fmt.Errorf("publish: %v; restore: %w", err, e)
			}
		}
		return err
	}
	return os.RemoveAll(backup)
}

func generate(c config.Config, out string) error {
	variants := map[string]images.Variant{}
	var sources []string
	err := filepath.WalkDir(c.Content, func(filename string, d fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}
		if filename == c.Content {
			return nil
		}
		if d.Type()&os.ModeSymlink != 0 {
			return fmt.Errorf("symlinks are not supported: %s", filename)
		}
		if strings.HasPrefix(d.Name(), ".") {
			if d.IsDir() {
				return filepath.SkipDir
			}
			return nil
		}
		rel, err := filepath.Rel(c.Content, filename)
		if err != nil {
			return err
		}
		rel = filepath.ToSlash(rel)
		first := strings.Split(rel, "/")[0]
		if first == "_images" || first == "_theme" {
			return fmt.Errorf("reserved content folder %s", first)
		}
		if d.IsDir() {
			return nil
		}
		if !d.Type().IsRegular() {
			return fmt.Errorf("unsupported file: %s", filename)
		}
		if !strings.Contains(rel, "/") && !strings.EqualFold(rel, "about.md") && !isFrontpageFile(rel) {
			return fmt.Errorf("content files must be inside project folders: %s", rel)
		}
		if strings.EqualFold(path.Ext(rel), ".md") {
			sources = append(sources, rel)
			return nil
		}
		if strings.EqualFold(path.Ext(rel), ".html") {
			return fmt.Errorf("HTML assets may collide with generated pages: %s", rel)
		}
		b, err := os.ReadFile(filename)
		if err != nil {
			return err
		}
		if err = write(out, rel, b); err != nil {
			return err
		}
		v, err := images.Process(filename, out, rel, c.ImageWidth)
		if err != nil {
			return err
		}
		if v.WebP != "" {
			variants[rel] = v
		}
		return nil
	})
	if err != nil {
		return err
	}
	tpl, err := template.New("theme").Funcs(template.FuncMap{
		"join":      strings.Join,
		"link":      markdown.LocalURL,
		"asset":     assetURL,
		"pathURL":   markdown.PathURL,
		"pageURL":   pageURL,
		"hasPrefix": strings.HasPrefix,
		"eqFold":    strings.EqualFold,
		"t":         func(key string, args ...any) string { return i18n.T(c.Lang, key, args...) },
		"isSection": i18n.IsSectionMatch,
	}).ParseFS(theme.Files, "templates/*.html")
	if err != nil {
		return err
	}
	overrides, err := filepath.Glob(filepath.Join(c.Templates, "*.html"))
	if err != nil {
		return err
	}
	if len(overrides) > 0 {
		tpl, err = tpl.ParseFiles(overrides...)
		if err != nil {
			return fmt.Errorf("templates: %w", err)
		}
	}
	static, err := fs.ReadDir(theme.Files, "static")
	if err != nil {
		return err
	}
	for _, f := range static {
		b, err := theme.Files.ReadFile("static/" + f.Name())
		if err != nil {
			return err
		}
		if err = write(out, "_theme/"+f.Name(), b); err != nil {
			return err
		}
	}
	if err = write(out, "_theme/accent.css", []byte(":root { --color-accent: "+c.Accent+"; }\n")); err != nil {
		return err
	}
	var pages []Page
	var introTitle string
	var introHTML template.HTML
	tags := map[string]bool{}
	for _, file := range sources {
		b, err := os.ReadFile(filepath.Join(c.Content, filepath.FromSlash(file)))
		if err != nil {
			return err
		}
		m, body, err := markdown.Parse(b)
		if err != nil {
			return fmt.Errorf("%s: %w", file, err)
		}
		if isFrontpageFile(file) {
			if m.Title == "" {
				lines := bytes.Split(body, []byte("\n"))
				for i, line := range lines {
					trimmed := bytes.TrimSpace(line)
					if len(trimmed) == 0 {
						continue
					}
					if bytes.HasPrefix(trimmed, []byte("# ")) {
						m.Title = string(bytes.TrimSpace(trimmed[2:]))
						lines = append(lines[:i], lines[i+1:]...)
						body = bytes.Join(lines, []byte("\n"))
					}
					break
				}
			}
			introTitle = m.Title
			rendered, err := markdown.Render(body, file, "./", variants)
			if err != nil {
				return fmt.Errorf("%s: %w", file, err)
			}
			introHTML = rendered
			continue
		}
		parts := strings.Split(file, "/")
		var group string
		if parts[0] == "blog" {
			group = "blog"
		} else if parts[0] == "about" || file == "about.md" {
			group = "about"
		} else if parts[0] == "projects" && len(parts) > 2 {
			group = parts[1]
		} else {
			group = parts[0]
		}
		if m.Title == "" {
			m.Title = strings.TrimSuffix(path.Base(file), path.Ext(file))
			if m.Title == "index" {
				if len(parts) > 1 && parts[len(parts)-1] == "index.md" {
					m.Title = parts[len(parts)-2]
				} else {
					m.Title = group
				}
			}
			m.Title = strings.ReplaceAll(m.Title, "-", " ")
		}
		p := Page{Meta: m, Group: group, URL: strings.TrimSuffix(file, path.Ext(file)) + ".html"}
		prefix := strings.Repeat("../", strings.Count(p.URL, "/"))
		p.HTML, err = markdown.Render(body, file, prefix, variants)
		if err != nil {
			return fmt.Errorf("%s: %w", file, err)
		}
		coverTarget := m.Cover
		if coverTarget == "" {
			if m.Photo != "" {
				coverTarget = m.Photo
			} else if m.Avatar != "" {
				coverTarget = m.Avatar
			}
		}
		if coverTarget == "" && p.Group == "about" {
			for _, candidate := range []string{"profile.jpg", "profile.jpeg", "profile.png", "profile.webp", "avatar.jpg", "avatar.jpeg", "avatar.png", "avatar.webp"} {
				candidateRel := path.Join(path.Dir(file), candidate)
				if _, ok := variants[candidateRel]; ok {
					coverTarget = candidate
					break
				}
				if _, err := os.Stat(filepath.Join(c.Content, filepath.FromSlash(candidateRel))); err == nil {
					coverTarget = candidate
					break
				}
			}
		}
		if coverTarget != "" {
			u, err := url.Parse(coverTarget)
			if err != nil {
				return err
			}
			if u.Scheme != "" || u.Host != "" {
				p.CoverURL = coverTarget
			} else {
				key := path.Clean(path.Join(path.Dir(file), u.Path))
				if strings.HasPrefix(u.Path, "/") {
					key = strings.TrimPrefix(u.Path, "/")
				}
				if key == ".." || strings.HasPrefix(key, "../") {
					return fmt.Errorf("%s: cover escapes content", file)
				}
				if _, err := os.Stat(filepath.Join(c.Content, filepath.FromSlash(key))); err != nil {
					return fmt.Errorf("%s: cover: %w", file, err)
				}
				p.CoverURL = key
				p.CoverImage = variants[key]
			}
		}
		for _, tag := range m.Tags {
			tags[tag] = true
		}
		pages = append(pages, p)
	}
	sort.SliceStable(pages, func(i, j int) bool {
		if pages[i].Date != pages[j].Date {
			return pages[i].Date > pages[j].Date
		}
		return pages[i].URL < pages[j].URL
	})
	for i := range pages {
		p := &pages[i]
		prefix := strings.Repeat("../", strings.Count(p.URL, "/"))
		sec := p.Group
		if sec != "blog" && sec != "about" {
			sec = "projects"
		}
		data := view{Site: c, Prefix: prefix, Title: p.Title, Description: p.Description, Section: sec, Page: p, Canonical: canonical(c.BaseURL, p.URL)}
		name := "detail.html"
		if p.Template != "" {
			name = p.Template
		} else if p.Group == "blog" {
			name = "post.html"
		} else if p.Group == "about" {
			name = "page.html"
		}
		if err := render(tpl, name, out, p.URL, data); err != nil {
			return err
		}
	}

	var projects []Page
	var posts []Page
	hasAbout := false
	for i := range pages {
		p := &pages[i]
		if p.Group == "blog" {
			posts = append(posts, *p)
		} else if p.Group == "about" {
			hasAbout = true
		} else {
			projects = append(projects, *p)
		}
	}
	groups := map[string][]Page{}
	for i := range projects {
		p := &projects[i]
		groups[p.Group] = append(groups[p.Group], *p)
	}
	var names []string
	for name := range groups {
		names = append(names, name)
	}
	sort.Strings(names)
	var projectGroups []Group
	for _, name := range names {
		projectGroups = append(projectGroups, Group{Name: name, Pages: groups[name]})
	}
	var tagList []string
	for tag := range tags {
		tagList = append(tagList, tag)
	}
	sort.Strings(tagList)

	var featured []Page
	for i := range projects {
		if len(featured) < 5 {
			featured = append(featured, projects[i])
		}
	}
	var recentPosts []Page
	for i := range posts {
		if len(recentPosts) < 5 {
			recentPosts = append(recentPosts, posts[i])
		}
	}
	var activity []Page
	for i := range pages {
		p := &pages[i]
		if p.Group != "about" {
			if len(activity) < 6 {
				activity = append(activity, *p)
			}
		}
	}

	if introTitle == "" && len(introHTML) == 0 {
		for i := range pages {
			p := &pages[i]
			if p.Group == "about" {
				introTitle = p.Title
				introHTML = p.HTML
				break
			}
		}
	}

	indexData := view{
		Site:        c,
		Prefix:      "./",
		Title:       c.Title,
		Description: c.Description,
		Canonical:   canonical(c.BaseURL, "index.html"),
		Section:     "home",
		Groups:      projectGroups,
		Tags:        tagList,
		Posts:       recentPosts,
		Featured:    featured,
		Activity:    activity,
		IntroTitle:  introTitle,
		IntroHTML:   introHTML,
	}
	if err := render(tpl, "index.html", out, "index.html", indexData); err != nil {
		return err
	}

	projectsData := view{
		Site:        c,
		Prefix:      "../",
		Title:       i18n.T(c.Lang, "projects") + " — " + c.Title,
		Description: i18n.T(c.Lang, "projects_lead"),
		Canonical:   canonical(c.BaseURL, "projects/index.html"),
		Section:     "projects",
		Groups:      projectGroups,
		Tags:        tagList,
		Featured:    featured,
	}
	if err := render(tpl, "projects.html", out, "projects/index.html", projectsData); err != nil {
		return err
	}

	var postTagList []string
	postTagsMap := map[string]bool{}
	for _, post := range posts {
		for _, tag := range post.Tags {
			postTagsMap[tag] = true
		}
	}
	for tag := range postTagsMap {
		postTagList = append(postTagList, tag)
	}
	sort.Strings(postTagList)

	blogData := view{
		Site:        c,
		Prefix:      "../",
		Title:       i18n.T(c.Lang, "writing") + " — " + c.Title,
		Description: i18n.T(c.Lang, "writing_lead"),
		Canonical:   canonical(c.BaseURL, "blog/index.html"),
		Section:     "blog",
		Tags:        postTagList,
		Posts:       posts,
	}
	if err := render(tpl, "blog.html", out, "blog/index.html", blogData); err != nil {
		return err
	}

	if !hasAbout {
		var aboutCoverURL string
		var aboutCoverImage images.Variant
		for _, candidate := range []string{"about/profile.jpg", "about/profile.jpeg", "about/profile.png", "about/profile.webp", "about/avatar.jpg", "about/avatar.jpeg", "about/avatar.png", "about/avatar.webp"} {
			if v, ok := variants[candidate]; ok {
				aboutCoverURL = candidate
				aboutCoverImage = v
				break
			}
		}
		aboutData := view{
			Site:        c,
			Prefix:      "../",
			Title:       i18n.T(c.Lang, "about") + " — " + c.Title,
			Description: c.Description,
			Canonical:   canonical(c.BaseURL, "about/index.html"),
			Section:     "about",
			Page: &Page{
				Meta: markdown.Meta{
					Title:       i18n.T(c.Lang, "about"),
					Description: c.Description,
				},
				Group:      "about",
				URL:        "about/index.html",
				CoverURL:   aboutCoverURL,
				CoverImage: aboutCoverImage,
				HTML:       template.HTML(i18n.T(c.Lang, "default_about_html", c.Author)),
			},
		}
		if err := render(tpl, "page.html", out, "about/index.html", aboutData); err != nil {
			return err
		}
	}
	return write(out, ".nojekyll", nil)
}

func canonical(base, rel string) string {
	if base == "" {
		return ""
	}
	return strings.TrimRight(base, "/") + "/" + markdown.PathURL(rel)
}
func render(t *template.Template, name, out, file string, v view) error {
	var buf bytes.Buffer
	if err := t.ExecuteTemplate(&buf, name, v); err != nil {
		return fmt.Errorf("render %s: %w", file, err)
	}
	return write(out, file, buf.Bytes())
}
func write(out, rel string, b []byte) error {
	filename := filepath.Join(out, filepath.FromSlash(rel))
	if err := os.MkdirAll(filepath.Dir(filename), 0755); err != nil {
		return err
	}
	return os.WriteFile(filename, b, 0644)
}

func assetURL(raw, prefix string) string {
	u, err := url.Parse(raw)
	if err == nil && (u.IsAbs() || u.Host != "") {
		return raw
	}
	raw = strings.TrimPrefix(raw, "/")
	if prefix == "./" || prefix == "" {
		return markdown.PathURL(raw)
	}
	return markdown.PathURL(prefix + raw)
}

func pageURL(raw, prefix string) string {
	u, err := url.Parse(raw)
	if err == nil && (u.IsAbs() || u.Host != "") {
		return raw
	}
	raw = strings.TrimPrefix(raw, "/")
	if prefix == "./" || prefix == "" {
		return markdown.PathURL(raw)
	}
	return markdown.PathURL(prefix + raw)
}

// Resolve existing ancestors too, so a missing output beneath a symlink cannot
// bypass the content/output overlap check.
func resolvedPath(filename string) (string, error) {
	absolute, err := filepath.Abs(filename)
	if err != nil {
		return "", err
	}
	resolved, err := filepath.EvalSymlinks(absolute)
	if err == nil {
		return resolved, nil
	}
	if !os.IsNotExist(err) {
		return "", err
	}
	parent := filepath.Dir(absolute)
	if parent == absolute {
		return "", err
	}
	resolved, err = resolvedPath(parent)
	if err != nil {
		return "", err
	}
	return filepath.Join(resolved, filepath.Base(absolute)), nil
}
